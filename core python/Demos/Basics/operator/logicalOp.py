# 1. and : if both are true then return true,
            # otherwise return false
print(True and True)

# 2. or : if both are false then return false,
            # otherwise return true
print(False or True)

# falsy : false,none,0,blank value like:'',[]
# eg.  print('' or 10)


# 3. not: opposite to operand
print((not True))