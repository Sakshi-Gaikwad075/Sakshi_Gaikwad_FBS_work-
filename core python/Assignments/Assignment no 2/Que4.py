# W A P to calculate area of triangle & rectangle

# Area of triangle
b = int(input("Enter base value:"))
h = int(input("Enter height value:"))

area = 1/2 * b * h

print("Area of Triangle = ",area)


# # Area of rectangle
l = int(input("Enter length:"))
br = int(input("Enter breadth:"))

a = l * br
print("Area of Reactangle =",a)